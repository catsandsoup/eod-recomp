void weapon_registry_unregister_impl(void) {
    const uint32_t iface = reg(4);
    int32_t count = lw(kWeaponRegistryCount);
    if (count <= 0) {
        set(2, count);
        return;
    }

    int32_t i = 0;
    uint32_t row = kWeaponRegistryAddr;
    while (i < count) {
        if (lwu(row + kRegistryOffIface) == iface) {
            count = lw(kWeaponRegistryCount) - 1;
            sw(kWeaponRegistryCount, static_cast<uint32_t>(count));
            const uint32_t last = kWeaponRegistryAddr + static_cast<uint32_t>(count) * kRegistryRowStride;
            sw(row + 0, lwu(last + 0));
            sw(row + 4, lwu(last + 4));
            sw(row + 8, lwu(last + 8));
        } else {
            row += kRegistryRowStride;
            ++i;
        }
        count = lw(kWeaponRegistryCount);
    }
    set(2, 0);
}

