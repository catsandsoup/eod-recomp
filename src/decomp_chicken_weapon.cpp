// 11. 0x0017E718 — ChickenWeaponDetonate (Impact & Detonation Handler)
// ============================================================================
void chicken_impact_impl(void) {
    const uint64_t saved_ra = reg64(31);
    const uint32_t saved_sp = reg(29);
    const uint32_t sp = saved_sp - 0xB0u;
    set(29, static_cast<int32_t>(sp));

    const uint32_t body = reg(4);
    const uint32_t arg1 = reg(5);
    const uint32_t arg2 = reg(6);
    const int32_t collision_class = static_cast<int32_t>(reg(7));
    const uint32_t arg4 = reg(8);

    if (lwu(body + kOffInFlight) != 0u && lwu(body + kOffImpactArmed) != 0u) {
        const bool is_terrain_class = (collision_class < kTerrainClassLimit);
        bool allow_detonate = true;

        if (is_terrain_class) {
            // Terrain/low-class hits detonate only in Mortar or Rain mode.
            const uint32_t cheats = lwu(kCheatFlagsAddr);
            allow_detonate = (cheats & kCheatMaster) != 0u &&
                             (cheats & (kCheatMortar | kCheatRain)) != 0u;
        }

        if (allow_detonate && collision_class < kMaxDetonateClass) {
            const uint32_t desc_buf = sp + 0x00u;
            copy_vec3(desc_buf, body + kOffWorldPos);
            sw(desc_buf + 0x0Cu, kBitsBlastRadius);
            sw(desc_buf + 0x10u, 1u);

            if (is_terrain_class) {
                set(4, static_cast<int32_t>(body + kOffRegionId));
                set(5, static_cast<int32_t>(desc_buf));
                set64(31, 0x0017E7D8u);
                f_00212600();
            }

            // Spawn explosion particle burst (type 3, 20 particles).
            set(4, 3);
            set(5, static_cast<int32_t>(desc_buf));
            set(6, 0x14);
            set64(31, 0x0017E7E8u);
            f_00177348();

            // Apply radial shockwave blast (7.5m radius, 25000 N impulse).
            set(4, static_cast<int32_t>(body + kOffWorldPos));
            set(5, lw(body + kOffOwnerIndex));
            g_ee.fpr[12].u = kBitsBlastRadius;
            g_ee.fpr[13].u = kBitsBlastForce;
            set64(31, 0x0017E804u);
            f_0017DA58();

            // Stop flight-loop SFX emitter.
            const uint32_t flight_sfx = lwu(body + kOffFlightSfx);
            if (flight_sfx != 0u) {
                sw(flight_sfx + kSfxOffActive, 0u);
                sw(flight_sfx + kSfxOffStop, 1u);
            }

            // Play detonation SFX at impact position.
            if (lwu(body + kOffBlastSfx) != 0u) {
                copy_vec3(body + kOffBlastSfxPos, body + kOffWorldPos);
                trigger_sfx_emitter(lwu(body + kOffBlastSfx), false);
            }

            // Retire projectile on next update tick.
            sw(body + kOffInFlight, 0u);
            sw(body + kOffPendingRetire, 1u);
        }
    }

    // Always run base rigid-body collision response.
    set(4, static_cast<int32_t>(body));
    set(5, static_cast<int32_t>(arg1));
    set(6, static_cast<int32_t>(arg2));
    set(7, collision_class);
    set(8, static_cast<int32_t>(arg4));
    set64(31, 0x0017E894u);
    f_0017D338();

    set64(31, saved_ra);
    set(29, static_cast<int32_t>(saved_sp));
}

