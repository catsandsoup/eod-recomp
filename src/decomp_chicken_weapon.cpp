// 7. 0x0017E440 — ChickenWeaponGetHudStatus
// ============================================================================
void chicken_weapon_get_hud_status_impl(void) {
    const uint32_t iface = reg(4);
    const uint32_t out_str = reg(5);
    const uint32_t out_ready = reg(6);
    const int32_t state = lw(iface + 4u); // body + kOffReloadState

    switch (state) {
    case kStateCooldown:
        sw(out_ready, 0u);
        sw(out_str, kHudStrReloading);
        set(2, static_cast<int32_t>(kHudStrReloading));
        return;
    case kStateAwaitingRelease:
        sw(out_str, 0u);
        sw(out_ready, 0u);
        set(2, 1);
        return;
    case kStateArmed:
        sw(out_ready, 1u);
        sw(out_str, kHudStrReady);
        set(2, static_cast<int32_t>(kHudStrReady));
        return;
    case kStateDisabled:
        sw(out_ready, 0u);
        sw(out_str, kHudStrDisabled);
        set(2, static_cast<int32_t>(kHudStrDisabled));
        return;
    default:
        sw(out_ready, 0u);
        sw(out_str, kHudStrFallback);
        set(2, static_cast<int32_t>(kHudStrFallback));
        return;
    }
}

