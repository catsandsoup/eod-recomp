        const float dir_x = fadd_ps2(fmul_ps2(lf(pose_buf + 24), kFwd), fmul_ps2(lf(pose_buf + 12), kUp));
        const float dir_y = fadd_ps2(fmul_ps2(lf(pose_buf + 28), kFwd), fmul_ps2(lf(pose_buf + 16), kUp));
