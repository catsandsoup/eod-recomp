// ============================================================================
// 10. 0x0017E5C8 — ChickenWeaponUpdate
// ============================================================================
void chicken_weapon_update_impl(void) {
    const uint64_t saved_ra = reg64(31);
    const uint32_t saved_sp = reg(29);
    const uint32_t sp = saved_sp - 0x60u;
    set(29, static_cast<int32_t>(sp));

    const uint32_t body = reg(4);

    // Finalize deferred retirement from a previous detonation.
    if (lwu(body + kOffPendingRetire) != 0u) {
        set(4, static_cast<int32_t>(body));
        set64(31, 0x0017E5F4u);
        f_0017F530();
    }

    // Advance Cooldown -> AwaitingRelease strictly when deadline < race_clock.
    if (lw(body + kOffReloadState) == kStateCooldown) {
        if (fcmp_lt(lf(body + kOffCooldownDeadline), lf(kRaceClockAddr))) {
            sw(body + kOffReloadState, static_cast<uint32_t>(kStateAwaitingRelease));
        }
    }

    // If neither Weapon nor Rain cheat is active, park the chicken underground.
    const uint32_t cheats = lwu(kCheatFlagsAddr);
    const bool weapon_or_rain = (cheats & kCheatMaster) != 0u &&
                                (cheats & (kCheatWeapon | kCheatRain)) != 0u;
    if (!weapon_or_rain) {
        park_chicken_underground(body, sp + 0x00u, 0x0017E64Cu, 0x0017E6ACu);
        sw(body + kOffLinearVel + 0, 0u);
        sw(body + kOffLinearVel + 4, 0u);
        sw(body + kOffLinearVel + 8, 0u);
    }

    // In Rain mode, spawn a sky chicken whenever this projectile is not in flight.
    if (lwu(body + kOffInFlight) == 0u) {
        const uint32_t cur_cheats = lwu(kCheatFlagsAddr);
        if ((cur_cheats & kCheatMaster) != 0u && (cur_cheats & kCheatRain) != 0u) {
            set(4, static_cast<int32_t>(body));
            set64(31, 0x0017E6ECu);
            f_0017EC58();
        }
    }

    // Step projectile flight effects and base rigid-body physics.
    set(4, static_cast<int32_t>(body));
    set64(31, 0x0017E6F4u);
    f_0017F4E0();

    set(4, static_cast<int32_t>(body));
    set64(31, 0x0017E6FCu);
    f_0017BBC0();

    set64(31, saved_ra);
    set(29, static_cast<int32_t>(saved_sp));
}

