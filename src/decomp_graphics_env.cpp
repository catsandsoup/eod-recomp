// ---- 0x353470 TextureSlotNoteDistance(int slot; f12 depth, f13 batch_scale) -----------------
// Tracks per-slot minimum scaled camera distance at slot+0x30 for dynamic texture streaming.
void texture_slot_note_distance() {
    const int32_t slot = static_cast<int32_t>(reg(4));
    if (slot == -1) {
        set(2, -1);
        return;
    }
    const uint32_t entry = lwu(kTexSlotTable) + static_cast<uint32_t>(slot) * kTexSlotStride;
    if (lw(kTexMipDistEnable) == 0) {
        set(2, 0x003E0000);
        return;
    }
    if (lw(entry + 0x34) == 0) {
        set(2, 0x003E0000);
        return;
    }
    const float clamped_depth = fmax_ps2(g_ee.fpr[12].f, bf(kFltOne));
    const float scaled = fmul_ps2(fmul_ps2(lf(kTexMipDistScale), clamped_depth), g_ee.fpr[13].f);
    const float best = fmin_ps2(scaled, lf(entry + 0x30));
    sf(entry + 0x30, best);
    set(2, 0x003E0000);
}

