// ---- 0x35B3D0 Vu1WriteCameraPacket() --------------------------------------------------------
// Builds the 18-qword VU1 camera packet (UNPACK V4-32 16 qwords to VU1 qwords 1..16):
//   q1..4  (pkt+0x20): viewport matrix (with NEGATIVE sy = fx * (-14/15 / aspect_x) * guard_y / near)
//   q5..8  (pkt+0x60): projection * viewport-scale matrix (via 0x38A5D0)
//   q9..12 (pkt+0xA0): guard-band clip-space projection matrix
//   q13..16(pkt+0xE0): view matrix (R^T and -R^T * t from 0x3E57A8/0x3E57CC; q16.w = fx)
void vu1_write_camera_packet() {
    Frame f(0x110);
    set(4, 0x12);
    call(f_00366D30, 0x35B428);
    const uint32_t pkt = reg(2);
    if (pkt != 0) {
        // DMA CNT qwc=17 + STMOD 0 + STCYCL 1,1
        sw(pkt + 0x00, 0x10000011u);
        sw(pkt + 0x04, 0u);
        sw(pkt + 0x08, 0x05000000u);
        sw(pkt + 0x0C, 0x01000101u);

        // MSCAL (0x24D8 >> 3) twice, marker 0x6666, UNPACK V4-32 count=16 addr=1 USN=1
        constexpr uint32_t kMscalWait = 0x1400049Bu;
        sw(pkt + 0x10, kMscalWait);
        sw(pkt + 0x14, kMscalWait);
        sw(pkt + 0x18, 0x00006666u);
        sw(pkt + 0x1C, 0x6C104001u);

        const float near_z = lf(kProjParams + 0x00);
        const float far_z = lf(kProjParams + 0x04);
        const float fov_scale = lf(kProjParams + 0x0C);
        const float vp_x = lf(kVu1Viewport + 0x00);
        const float vp_y = lf(kVu1Viewport + 0x04);
        const float vp_w = lf(kVu1Viewport + 0x08);
        const float vp_h = lf(kVu1Viewport + 0x0C);
        const float guard_w = lf(kVu1GuardBand + 0x00);
        const float guard_h = lf(kVu1GuardBand + 0x04);
        const float aspect_x = lf(kDisplayAspectXScale);

        const float half = bf(kFltHalf);
        const float one = bf(kFltOne);
        const float near_far = fmul_ps2(far_z, near_z);
        const float depth_span = fsub_ps2(far_z, near_z);

        const float fx = fmul_ps2(fmul_ps2(fov_scale, vp_w), half);
        const float sy_aspect = fdiv_ps2(bf(kFltNegNtscYScale), aspect_x);

        const float gs_bias = bf(kFltGsCenterBias);
        const float cx = fsub_ps2(fadd_ps2(fadd_ps2(vp_x, gs_bias), fmul_ps2(vp_w, half)), bf(kFltHalfFbW));
        const float cy = fsub_ps2(fadd_ps2(fadd_ps2(vp_y, gs_bias), fmul_ps2(vp_h, half)), bf(kFltHalfFbH));

        const float z_scale = fdiv_ps2(fmul_ps2(near_far, bf(kFltZScaleNum)), depth_span);
        const float z_bias = fdiv_ps2(fadd_ps2(fmul_ps2(near_z, bf(kFltZBiasNum)), far_z), depth_span);

        const float guard_x_near = fdiv_ps2(fmul_ps2(near_z, guard_w), fx);
        const float guard_y_near = fdiv_ps2(fmul_ps2(near_z, guard_h), fx);

        const uint32_t q1 = pkt + 0x20;
        const uint32_t q5 = pkt + 0x60;
        const uint32_t q9 = pkt + 0xA0;
        const uint32_t tmp_mat = f.sp();

        // q5..8 = V_scale * P (via Mat4Multiply 0x38A5D0)
        set(4, static_cast<int32_t>(q5));
        call(f_0038AE78, 0x35B5B0);
        sf(q5 + 0x00, fx);
        sf(q5 + 0x14, fx);
        sw(q5 + 0x28, 0);
        sf(q5 + 0x2C, one);
        sf(q5 + 0x38, one);
        sw(q5 + 0x3C, 0);

        set(4, static_cast<int32_t>(tmp_mat));
        call(f_0038AE78, 0x35B5D0);
        sf(tmp_mat + 0x00, one);
        sf(tmp_mat + 0x14, sy_aspect);
        sf(tmp_mat + 0x28, z_scale);
        sf(tmp_mat + 0x30, cx);
        sf(tmp_mat + 0x34, cy);
        sf(tmp_mat + 0x38, z_bias);

        set(4, static_cast<int32_t>(q5));
        set(5, static_cast<int32_t>(tmp_mat));
        set(6, static_cast<int32_t>(q5));
        call(f_0038A5D0, 0x35B5F8);

        // q9..12 = guard-band clip-space projection
        set(4, static_cast<int32_t>(q9));
        call(f_0038AE78, 0x35B600);
        const float two_near = fadd_ps2(near_z, near_z);
        const float clip_x = fdiv_ps2(two_near, fadd_ps2(guard_x_near, guard_x_near));
        const float clip_y = fdiv_ps2(two_near, fadd_ps2(guard_y_near, guard_y_near));
        const float clip_z = fdiv_ps2(fadd_ps2(far_z, near_z), fsub_ps2(far_z, near_z));
        const float clip_w = fdiv_ps2(fmul_ps2(near_far, bf(kFltNegTwo)), fsub_ps2(far_z, near_z));
        sf(q9 + 0x00, clip_x);
        sf(q9 + 0x14, clip_y);
        sf(q9 + 0x28, clip_z);
        sf(q9 + 0x2C, one);
        sf(q9 + 0x38, clip_w);
        sw(q9 + 0x3C, 0);

        // q1..4 = viewport matrix (note negative sy in q2.y)
        set(4, static_cast<int32_t>(q1));
        call(f_0038AE78, 0x35B650);
        const float vp_sx = fdiv_ps2(fmul_ps2(fx, guard_x_near), near_z);
        const float vp_sy = fdiv_ps2(fmul_ps2(fmul_ps2(fx, sy_aspect), guard_y_near), near_z);
        sf(q1 + 0x00, vp_sx);
        sf(q1 + 0x14, vp_sy);
        sw(q1 + 0x28, kFltVpZScale);
        sf(q1 + 0x30, cx);
        sf(q1 + 0x34, cy);
        sw(q1 + 0x38, kFltVpZBias);
        sf(q1 + 0x3C, one);

        // q13..16 = view matrix: transpose 3x3 camera rotation at 0x3E57A8, translation = -R^T * t
        float r[9];
        for (int i = 0; i < 9; ++i) r[i] = lf(kCameraMatrix + static_cast<uint32_t>(i) * 4u);
        const float tx = lf(kCameraMatrix + 0x24);
        const float ty = lf(kCameraMatrix + 0x28);
        const float tz = lf(kCameraMatrix + 0x2C);
        const float vtx = fneg(madd3(tx, r[0], ty, r[1], tz, r[2]));
        const float vty = fneg(madd3(tx, r[3], ty, r[4], tz, r[5]));
        const float vtz = fneg(madd3(tx, r[6], ty, r[7], tz, r[8]));

        const uint32_t q13 = q1 + 0xC0;
        // Row 0 = column 0 of R
        sf(q13 + 0x00, r[0]);
        sf(q13 + 0x04, r[3]);
        sf(q13 + 0x08, r[6]);
        sw(q13 + 0x0C, 0);
        // Row 1 = column 1 of R
        sf(q13 + 0x10, r[1]);
        sf(q13 + 0x14, r[4]);
        sf(q13 + 0x18, r[7]);
        sw(q13 + 0x1C, 0);
        // Row 2 = column 2 of R
        sf(q13 + 0x20, r[2]);
        sf(q13 + 0x24, r[5]);
        sf(q13 + 0x28, r[8]);
        sw(q13 + 0x2C, 0);
        // Row 3 = -R^T * t, with q16.w overwritten with fov_scale * vp_w * 0.5f
        sf(q13 + 0x30, vtx);
        sf(q13 + 0x34, vty);
        sf(q13 + 0x38, vtz);
        sf(q13 + 0x3C, fmul_ps2(fmul_ps2(lf(kProjParams + 0x0C), lf(kVu1Viewport + 0x08)), half));

        set(4, 0x12);
        call(f_00366CD0, 0x35B858);
    }
    sw(kCameraDirty, 0);
    set(2, 0x003E0000);
}

// ---- 0x34D8A0 ViewportSet(x, y, w, h) -------------------------------------------------------
void viewport_set() {
    Frame f(0x20);
    int32_t x = static_cast<int32_t>(reg(4));
    int32_t y = static_cast<int32_t>(reg(5));
    const int32_t w = static_cast<int32_t>(reg(6));
    int32_t h = static_cast<int32_t>(reg(7));

    if (lw(kViewportBypassScale) == 0 && lw(kViewportYScaleEnable) != 0) {
        const int32_t half_screen_h = lw(kScreenHeight) / 2;
        const float y_scale = lf(kViewportYScale);
        const float half = bf(kFltHalf);
        h = fcvtw_ps2(fadd_ps2(fmul_ps2(static_cast<float>(h), y_scale), half));
        const int32_t dy = fcvtw_ps2(fadd_ps2(fmul_ps2(static_cast<float>(y - half_screen_h), y_scale), half));
        y = half_screen_h + dy;
    }

    sw(kViewportRect + 0x00, static_cast<uint32_t>(x));
    sw(kViewportRect + 0x04, static_cast<uint32_t>(y));
    sw(kViewportRect + 0x08, static_cast<uint32_t>(w));
    sw(kViewportRect + 0x0C, static_cast<uint32_t>(h));

    set(4, x);
    set(5, y);
    set(6, w);
    set(7, h);
    call(f_0035E200, 0x34D968);

    set(4, w);
    g_ee.fpr[12].u = lwu(kProjFov);
    set(29, static_cast<int32_t>(f.caller_sp));
    set64(31, f.ra);
    f_00353A20();
}

// ---- 0x35E200 Vu1SetViewport(x, y, w, h) ----------------------------------------------------
