#!/usr/bin/env python3
"""Compiles runtime/gs/vulkan/gs_shaders_vk.hlsl to SPIR-V for the Vulkan GS
renderer: runtime/gs/vulkan/gs_shaders_vk.inc (uint32 arrays, committed; the
normal build doesn't need the tools).

Needs glslangValidator, spirv-dis, spirv-as and spirv-val
(brew install glslang spirv-tools).  The HLSL is a copy of the Direct3D 11 source (runtime/gs/d3d11), built
with -DVK and -DVK_DRAW or -DVK_PASS so each module has one push-constant block.

glslang's HLSL front end has no [[vk::index]], so the dual-source blend output
of ps_draw (declared at location 1) is moved to location 0, index 1 here.
"""
import os
import re
import subprocess
import sys
import shutil
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "runtime", "gs", "vulkan", "gs_shaders_vk.hlsl")
OUT = os.path.join(ROOT, "runtime", "gs", "vulkan", "gs_shaders_vk.inc")
# entry, stage, section
ENTRIES = [
    ("vs_draw", "vert", "VK_DRAW"),
    ("ps_draw", "frag", "VK_DRAW"),
    ("vs_pass", "vert", "VK_PASS"),
    ("ps_convert_color", "frag", "VK_PASS"),
    ("ps_convert_depth", "frag", "VK_PASS"),
    ("ps_upload_color", "frag", "VK_PASS"),
    ("ps_upload_depth", "frag", "VK_PASS"),
    ("ps_readback_color", "frag", "VK_PASS"),
    ("ps_readback_depth", "frag", "VK_PASS"),
    ("ps_copy", "frag", "VK_PASS"),
]
DUAL_SOURCE = {"ps_draw"}


def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit("failed: %s\n%s%s" % (" ".join(cmd), r.stdout, r.stderr))
    return r.stdout


def compile_entry(tmp, entry, stage, section):
    spv = os.path.join(tmp, entry + ".spv")
    run(["glslangValidator", "-D", "-V", "-DVK", "-D" + section, "-S", stage, "-e", entry,
         "--target-env", "vulkan1.1", "-g0", SRC, "-o", spv])
    if entry in DUAL_SOURCE:
        asm = run(["spirv-dis", "--raw-id", "--no-header", spv])
        outputs = set(re.findall(r"%(\d+) = OpVariable %\d+ Output", asm))
        ids = [i for i in re.findall(r"OpDecorate %(\d+) Location 1\b", asm) if i in outputs]
        if len(ids) != 1:
            sys.exit("%s: expected one location-1 output, found %d" % (entry, len(ids)))
        vid = ids[0]
        asm = asm.replace("OpDecorate %%%s Location 1\n" % vid,
                          "OpDecorate %%%s Location 0\nOpDecorate %%%s Index 1\n" % (vid, vid))
        src = os.path.join(tmp, entry + ".spvasm")
        open(src, "w").write(asm)
        run(["spirv-as", "--target-env", "vulkan1.1", src, "-o", spv])
    run(["spirv-val", "--target-env", "vulkan1.1", spv])
    data = open(spv, "rb").read()
    return [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]


def main():
    tmp = tempfile.mkdtemp()
    out = ["// generated by tools/build_vk_shaders.py from runtime/gs/vulkan/gs_shaders_vk.hlsl - do not edit"]
    for entry, stage, section in ENTRIES:
        words = compile_entry(tmp, entry, stage, section)
        out.append("static const uint32_t k_spv_%s[] = {" % entry)
        for i in range(0, len(words), 8):
            out.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",")
        out.append("};")
    text = "\n".join(out) + "\n"
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    if not (os.path.exists(OUT) and open(OUT).read() == text):
        open(OUT, "w").write(text)
    shutil.rmtree(tmp)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
