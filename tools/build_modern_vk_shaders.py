#!/usr/bin/env python3
"""Compiles runtime/gs/vulkan/modern_vk.hlsl (the modern renderer's Vulkan
shaders) to SPIR-V: runtime/gs/vulkan/modern_vk_spv.inc (uint32 arrays,
committed; the normal build does not need the compiler).

Needs DXC (DirectXShaderCompiler) with SPIR-V output: set DXC to its path or
put dxc on PATH. Every entry is compiled on its own (shader model 6.0, Vulkan
1.1 target, -O3), so each module declares only the resources it uses.
"""
import os
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "runtime", "gs", "vulkan", "modern_vk.hlsl")
OUT = os.path.join(ROOT, "runtime", "gs", "vulkan", "modern_vk_spv.inc")

# (entry, stage); the list order is the order of the arrays in the output
ENTRIES = [
    ("vs_modern", "vs"), ("ps_modern", "ps"),
    ("vs_shadow", "vs"), ("ps_shadow", "ps"),
    ("vs_gsdepth", "vs"),
    ("vs_full", "vs"), ("ps_full", "ps"),
    ("ps_ao", "ps"), ("ps_bright", "ps"), ("ps_blur", "ps"), ("ps_comp", "ps"),
]


def main():
    dxc = os.environ.get("DXC") or shutil.which("dxc")
    if not dxc:
        sys.exit("dxc not found: set DXC to DirectXShaderCompiler's dxc")
    entries = ENTRIES
    extra = [a for a in sys.argv[1:] if a.startswith("-D")]
    tmp = tempfile.mkdtemp()
    out = ["// generated by tools/build_modern_vk_shaders.py from runtime/gs/vulkan/modern_vk.hlsl - do not edit"]
    try:
        for entry, stage in entries:
            spv = os.path.join(tmp, entry + ".spv")
            cmd = [dxc, "-spirv", "-T", stage + "_6_0", "-E", entry, "-fspv-target-env=vulkan1.1",
                   "-fvk-use-dx-layout", "-O3", "-Wno-ambig-lit-shift"] + extra + [SRC, "-Fo", spv]
            r = subprocess.run(cmd, capture_output=True, text=True)
            if r.returncode != 0:
                sys.exit("failed: %s\n%s%s" % (entry, r.stdout, r.stderr))
            data = open(spv, "rb").read()
            words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
            out.append("static const uint32_t k_mspv_%s[] = {" % entry)
            for i in range(0, len(words), 8):
                out.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",")
            out.append("};")
    finally:
        shutil.rmtree(tmp)
    text = "\n".join(out) + "\n"
    if not (os.path.exists(OUT) and open(OUT).read() == text):
        with open(OUT, "w", newline="\n") as f:
            f.write(text)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
