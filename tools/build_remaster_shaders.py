#!/usr/bin/env python3
"""Compiles runtime/remaster/shaders/remaster_pbr.hlsl to SPIR-V:
runtime/remaster/remaster_shaders_spv.inc (committed uint32 arrays).
Supports DXC or glslangValidator + spirv-opt + spirv-val.
"""
import os
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "runtime", "remaster", "shaders", "remaster_pbr.hlsl")
OUT = os.path.join(ROOT, "runtime", "remaster", "remaster_shaders_spv.inc")

ENTRIES = [
    ("vs_csm_depth", "vs"),
    ("ps_csm_alpha", "ps"),
    ("vs_pbr_main", "vs"),
    ("ps_pbr_cubemap", "ps"),
    ("ps_pbr_forward", "ps"),
    ("vs_resolve_quad", "vs"),
    ("ps_neutral_resolve", "ps"),
    ("vs_hud_2d", "vs"),
    ("ps_hud_2d", "ps"),
]


def _run(cmd, label):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"failed: {label}\n{r.stdout}{r.stderr}")
    return r.stdout


def main():
    dxc = os.environ.get("DXC") or shutil.which("dxc")
    glslang = os.environ.get("GLSLANG") or shutil.which("glslangValidator")
    spirv_opt = shutil.which("spirv-opt")
    spirv_val = shutil.which("spirv-val")
    if not dxc and not glslang:
        sys.exit("neither dxc nor glslangValidator found")

    tmp = tempfile.mkdtemp()
    stage_map = {"vs": "vert", "ps": "frag"}
    out_lines = [
        "// generated by tools/build_remaster_shaders.py from runtime/remaster/shaders/remaster_pbr.hlsl - do not edit"
    ]
    try:
        src_path = SRC
        if not dxc:
            src_text = open(SRC, "r", encoding="utf-8").read()
            src_text = re.sub(
                r"\[\[vk::push_constant\]\]\s+([A-Za-z_]\w*)\s+([A-Za-z_]\w*)\s*;",
                r"[[vk::push_constant]] ConstantBuffer<\1> \2;",
                src_text,
            )
            src_path = os.path.join(tmp, os.path.basename(SRC))
            with open(src_path, "w", encoding="utf-8", newline="\n") as f:
                f.write(src_text)

        for entry, stage in ENTRIES:
            spv = os.path.join(tmp, f"{entry}.spv")
            if dxc:
                _run([
                    dxc, "-spirv", "-T", f"{stage}_6_0", "-E", entry,
                    "-fspv-target-env=vulkan1.1", "-fvk-use-dx-layout", "-O3",
                    src_path, "-Fo", spv,
                ], entry)
            else:
                _run([
                    glslang, "-D", "-V", "-S", stage_map[stage], "-e", entry,
                    "--target-env", "vulkan1.1", "-g0", src_path, "-o", spv,
                ], entry)
                if spirv_opt:
                    opt_spv = os.path.join(tmp, f"{entry}.opt.spv")
                    _run([spirv_opt, "-O", "--target-env=vulkan1.1", spv, "-o", opt_spv], f"{entry} opt")
                    spv = opt_spv
                if spirv_val:
                    _run([spirv_val, "--target-env", "vulkan1.1", spv], f"{entry} val")

            data = open(spv, "rb").read()
            words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
            out_lines.append(f"[[maybe_unused]] static const uint32_t k_remaster_{entry}[] = {{")
            for i in range(0, len(words), 8):
                out_lines.append("    " + ", ".join(f"0x{w:08x}" for w in words[i:i + 8]) + ",")
            out_lines.append("};")
    finally:
        shutil.rmtree(tmp)

    text = "\n".join(out_lines) + "\n"
    if not (os.path.exists(OUT) and open(OUT, "r", encoding="utf-8").read() == text):
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
